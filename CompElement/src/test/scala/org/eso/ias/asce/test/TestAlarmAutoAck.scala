package org.eso.ias.asce.test

import org.eso.ias.asce.transfer.impls.{MinMaxThresholdTF, MinMaxThresholdTFJava}
import org.eso.ias.asce.{AsceStates, CompEleThreadFactory, ComputingElement}
import org.eso.ias.asce.transfer.{JavaTransfer, ScalaTransfer, TransferFunctionLanguage, TransferFunctionSetting}
import org.eso.ias.logging.IASLogger
import org.eso.ias.types.{Alarm, IASTypes, Identifier, IdentifierType, InOut, Priority}
import org.scalatest.flatspec.AnyFlatSpec

import java.util.Properties

class TestAlarmAutoAck extends AnyFlatSpec {

  /** The logger */
  private val logger = IASLogger.getLogger(this.getClass)

  // The ID of the DASU where the components runs
  val supervId = new Identifier("SupervId", IdentifierType.SUPERVISOR, None)
  val dasId = new Identifier("DASU-ID", IdentifierType.DASU, supervId)

  // The ID of the component to test
  val compId = new Identifier("AsceId", IdentifierType.ASCE, Option[Identifier](dasId))

  // The ID of the output generated by the component
  val outId = new Identifier("OutputId", IdentifierType.IASIO, Option(compId))

  // The IDs of the monitor point in input to pass when building a Component
  val requiredInputID = "ValueId"

  // The ID of the first MP in input
  val mpIIdentifier = new Identifier(requiredInputID, IdentifierType.IASIO, Option(compId))
  val inputMP = InOut.asInput(mpIIdentifier, IASTypes.LONG)

  // The input
  val initialInputs: Set[InOut[?]] = Set(inputMP)

  // Build the IASIO in output
  val output = InOut.asOutput(
    outId,
    IASTypes.ALARM)

  // The threshold to assess the validity from the arrival time of the input
  val validityThresholdInSecs = 5

  val props = new Properties()
  props.put(MinMaxThresholdTF.highOnPropName, "50")
  props.put(MinMaxThresholdTF.highOffPropName, "25")
  props.put(MinMaxThresholdTF.lowOffPropName, "-10")
  props.put(MinMaxThresholdTF.lowOnPropName, "-20")
  props.put(MinMaxThresholdTF.alarmPriorityPropName, Priority.HIGH.toString)

  behavior of "autoAck"

  it must "auto-ACK an alarm when autoAck is enabled (Scala TF)" in {
    logger.info("Testing auto-ACK with Scala TF")

    val tfSetting = new TransferFunctionSetting(
      "org.eso.ias.asce.transfer.impls.MinMaxThresholdTF",
      TransferFunctionLanguage.scala,
      None,
      new CompEleThreadFactory("TestAutoAckScala"))

    val comp: ComputingElement[Alarm] = new ComputingElement[Alarm](
      compId,
      output.asInstanceOf[InOut[Alarm]],
      initialInputs,
      tfSetting,
      validityThresholdInSecs,
      props) with ScalaTransfer[Alarm] {
      override val autoAck: Boolean = true
    }

    // Verify autoAck is enabled via anonymous class override
    assert(comp.autoAck, "autoAck should be true after anonymous class override")

    comp.initialize()
    assert(comp.getState() == AsceStates.InputsUndefined)

    // Trigger alarm SET — should be auto-ACKed immediately
    val in1 = inputMP.updateValue(Some(100L)).updateProdTStamp(System.currentTimeMillis())
    val ret1 = comp.update(Set(in1.toIASValue()))
    val outAlarm1 = ret1._1.get.value.get.asInstanceOf[Alarm]
    logger.info("Output produced: {}", outAlarm1.toString)
    assert(outAlarm1.isSet, "Alarm should be SET")
    assert(comp.output.value.get.asInstanceOf[Alarm].isAcked, "Alarm should be auto-ACKed after update()")

    // Clear alarm — should remain ACKed
    val in2 = inputMP.updateValue(Some(0L)).updateProdTStamp(System.currentTimeMillis())
    val ret2 = comp.update(Set(in2.toIASValue()))
    val outAlarm2 = ret2._1.get.value.get.asInstanceOf[Alarm]
    logger.info("Output produced: {}", outAlarm2.toString)
    assert(outAlarm2.isCleared, "Alarm should be CLEARED")
    assert(outAlarm2.isAcked, "Cleared alarm should remain ACKed")

    // Re-trigger SET — should be auto-ACKed again (not a one-time only behavior)
    val in3 = inputMP.updateValue(Some(100L)).updateProdTStamp(System.currentTimeMillis())
    val ret3 = comp.update(Set(in3.toIASValue()))
    val outAlarm3 = ret3._1.get.value.get.asInstanceOf[Alarm]
    logger.info("Output produced: {}", outAlarm3.toString)
    assert(outAlarm3.isSet, "Alarm should be SET again")
    assert(comp.output.value.get.asInstanceOf[Alarm].isAcked, "Re-set alarm should be auto-ACKed again")

    comp.shutdown()
  }

  it must "auto-ACK an alarm with Java TF" in {
    logger.info("Testing auto-ACK with Java TF")

    val tfSetting = new TransferFunctionSetting(
      "org.eso.ias.asce.transfer.impls.MinMaxThresholdTFJava",
      TransferFunctionLanguage.java,
      None,
      new CompEleThreadFactory("TestAutoAckJava"))

    val javaProps = new Properties()
    javaProps.put(MinMaxThresholdTFJava.highOnPropName, "50")
    javaProps.put(MinMaxThresholdTFJava.highOffPropName, "25")
    javaProps.put(MinMaxThresholdTFJava.lowOffPropName, "-10")
    javaProps.put(MinMaxThresholdTFJava.lowOnPropName, "-20")
    javaProps.put(MinMaxThresholdTF.alarmPriorityPropName, Priority.HIGH.toString)

    val comp: ComputingElement[Alarm] = new ComputingElement[Alarm](
      compId,
      output.asInstanceOf[InOut[Alarm]],
      initialInputs,
      tfSetting,
      validityThresholdInSecs,
      javaProps) with JavaTransfer[Alarm] {
      override val autoAck: Boolean = true
    }

    // Verify autoAck is enabled via anonymous class override
    assert(comp.autoAck, "autoAck should be true after anonymous class override")

    comp.initialize()

    // Trigger alarm SET
    val in1 = inputMP.updateValue(Some(100L)).updateProdTStamp(System.currentTimeMillis())
    comp.update(Set(in1.toIASValue()))
    assert(comp.output.value.get.asInstanceOf[Alarm].isSet)
    assert(comp.output.value.get.asInstanceOf[Alarm].isAcked, "Java TF: Alarm should be auto-ACKed")

    // Clear and re-set verifies repeated auto-ACK
    val in2 = inputMP.updateValue(Some(0L)).updateProdTStamp(System.currentTimeMillis())
    comp.update(Set(in2.toIASValue()))

    val in3 = inputMP.updateValue(Some(100L)).updateProdTStamp(System.currentTimeMillis())
    comp.update(Set(in3.toIASValue()))
    assert(comp.output.value.get.asInstanceOf[Alarm].isSet)
    assert(comp.output.value.get.asInstanceOf[Alarm].isAcked, "Java TF: Re-set alarm should be auto-ACKed again")

    comp.shutdown()
  }

  it must "NOT auto-ACK when autoAck is disabled (default)" in {
    logger.info("Testing that auto-ACK is disabled by default")

    val tfSetting = new TransferFunctionSetting(
      "org.eso.ias.asce.transfer.impls.MinMaxThresholdTF",
      TransferFunctionLanguage.scala,
      None,
      new CompEleThreadFactory("TestNoAutoAck"))

    // No override — autoAck defaults to false
    val comp: ComputingElement[Alarm] = new ComputingElement[Alarm](
      compId,
      output.asInstanceOf[InOut[Alarm]],
      initialInputs,
      tfSetting,
      validityThresholdInSecs,
      props) with ScalaTransfer[Alarm]

    // Verify autoAck is disabled by default
    assert(!comp.autoAck, "autoAck should be false by default")

    comp.initialize()

    val in1 = inputMP.updateValue(Some(100L)).updateProdTStamp(System.currentTimeMillis())
    val ret1 = comp.update(Set(in1.toIASValue()))
    val outAlarm1 = ret1._1.get.value.get.asInstanceOf[Alarm]
    logger.info("Output produced: {}", outAlarm1.toString)
    assert(outAlarm1.isSet, "Alarm should be SET")
    assert(!comp.output.value.get.asInstanceOf[Alarm].isAcked, "Alarm should NOT be auto-ACKed when autoAck is false")

    comp.shutdown()
  }

}
