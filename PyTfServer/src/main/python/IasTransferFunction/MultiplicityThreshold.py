import logging

from IasBasicTypes.Alarm import Alarm
from IasBasicTypes.AlarmState import AlarmState
from IasBasicTypes.IasType import IASType
from IasBasicTypes.OperationalMode import OperationalMode
from IasBasicTypes.Priority import Priority
from IasBasicTypes.Validity import Validity
from IasTransferFunction.TransferFunction import TransferFunction


class MultiplicityThreshold(TransferFunction):
    '''
    The python TF implementation of the Multiplicity transfer function.

    The IASIOs in input to this TF are only alarms.
    The alarm generated by this TF activates when the number
    of alarms in input is equal or greater than the threshold retrieved
    from the properties.

    The priority of the alarm produced by this TF is the highest of the priorities
    of the alarms in input unless a priority is passed by setting the alarm priority property
    in the CDB.

    Since #153, the multiplicity TF propagates the properties of the inputs to the output:
    - only the properties of the inputs that are SET are propagated in the output
    - if the same property is present in more inputs, their values will be merged in the output
    '''

    threshold_prop_name = "org.eso.ias.tf.mutliplicity.threshold"
    alarm_priority_prop_name = "org.eso.ias.tf.alarm.priority"
    input_alarms_set_prop_name = "IdsOfAlarmsSet"

    def __init__(self, asceId, asceRunningId, validityTimeFrame, props, instance):
        '''
        Constructor

        :param asceId: the ID of the ASCE
        :param asceRunningId: the running ID of the ASCE
        :param validityTimeFrame: the validity time frame (long)
        :param props: the user defined properties dictionary
        :param instance: the template instance number or None
        '''
        super().__init__(asceId, asceRunningId, validityTimeFrame, props, instance)
        self.logger = logging.getLogger(self.__class__.__name__)
        self.logger.info("MultiplicityThreshold built for ASCE %s", self.asceRunningId)

        if self.props is None:
            self.props = {}

        threshold_str = self.props.get(self.threshold_prop_name)
        if threshold_str is None:
            raise ValueError(
                "Missing required property: " + self.threshold_prop_name)
        elif threshold_str == "":
            raise ValueError(
                "Empty value for property: " + self.threshold_prop_name)
        else:
            try:
                self.threshold = int(threshold_str)
                if self.threshold < 1:
                    raise ValueError(
                        "" + self.threshold_prop_name + ": value must be >= 1, got " + str(self.threshold))
            except ValueError:
                raise ValueError(
                    "" + self.threshold_prop_name + ": invalid value " + str(threshold_str))

        priority_str = self.props.get(self.alarm_priority_prop_name)
        if priority_str is not None:
            self.priorityFromCDB = Priority.value_of(priority_str)
        else:
            self.priorityFromCDB = Priority.get_default_priority()

    def initialize(self, inputsInfo, outputInfo):
        '''
        Check that all the inputs and the output are alarms.

        :param inputsInfo: the IDs and types of the inputs
        :param outputInfo: the ID and type of the output
        '''
        self.logger.debug("Initializing MultiplicityThreshold for %s", self.asceRunningId)

        inputTypes = set(ias.iasType for ias in inputsInfo)
        assert inputTypes == {IASType.ALARM}, \
            "All inputs must be ALARM for ASCE %s" % self.asceRunningId
        assert outputInfo.iasType == IASType.ALARM, \
            "The output must be an ALARM for ASCE %s" % self.asceRunningId

        self.logger.info(
            "The TF accepts %d inputs with a threshold of %d",
            len(inputsInfo), self.threshold)
        assert len(inputsInfo) >= self.threshold, \
            "Too few inputs to activate this TF for ASCE %s" % self.asceRunningId

        self.logger.debug("MultiplicityThreshold initialized")

    def shutdown(self):
        '''
        Shutdown the TF.
        '''
        pass

    def getOutputMode(self, modes):
        '''
        The mode of the output depends on the modes of the inputs:
        it is UNKNOWN if the modes of the inputs differ, otherwise it is
        the common operational mode of the inputs.

        :param modes: the operational modes of the inputs
        :return: the mode to assign to the output
        '''
        uniqueModes = set(OperationalMode.fromString(m) for m in modes)
        if len(uniqueModes) == 1:
            return list(uniqueModes)[0]
        else:
            return OperationalMode.UNKNOWN

    def getPropsOfOutput(self, propsList):
        '''
        Get and return the properties of the output by the properties of the inputs.

        :param propsList: the properties of the inputs that are set
        :return: the properties to assign to the output
        '''
        merged = []
        for propMap in propsList:
            merged.extend(propMap.items())

        if not merged:
            return {}

        grouped = {}
        for k, v in merged:
            if k not in grouped:
                grouped[k] = []
            grouped[k].append(v)

        return {k: ",".join(vs) for k, vs in grouped.items()}

    def buildValidityConstraint(self, isSet, activeAlarms, inactiveAlarms):
        '''
        Set the validity constraint to apply to the TF.

        The validity depends on the validity of the inputs that contribute
        to the determination of the output.
        See https://github.com/IntegratedAlarmSystem-Group/ias/issues/201

        :param isSet: True if the output is set, False if cleared
        :param activeAlarms: the alarms in input that are SET
        :param inactiveAlarms: the alarms in input that are CLEARED
        :return: the IDs of the alarms to use to set the validity of the output,
                 or None if no constraint applies
        '''
        validSetAlarms = [a for a in activeAlarms
                          if a.validity == Validity.RELIABLE]
        validUnsetAlarms = [a for a in inactiveAlarms
                            if a.validity == Validity.RELIABLE]

        totalAlarms = len(activeAlarms) + len(inactiveAlarms)

        if isSet and len(validSetAlarms) >= self.threshold:
            return {a.id for a in validSetAlarms}
        elif not isSet and len(validUnsetAlarms) > totalAlarms - self.threshold:
            return {a.id for a in validUnsetAlarms}
        else:
            return None

    def eval(self, compInputs, actualOutput):
        '''
        Run the TF.

        :param compInputs: the inputs (Map of IASIOs with their IDs as keys)
        :param actualOutput: the actual output (IASIO)
        :return: the new output of the ASCE (IASIO)
        '''
        self.logger.debug(
            "Running python MultiplicityThreshold TF of ASCE %s",
            self.asceRunningId)

        activeAlarms = [v for v in compInputs.values()
                        if v.value is not None and v.value.is_set()]
        inactiveAlarms = [v for v in compInputs.values()
                          if v.value is not None and not v.value.is_set()]

        actualAlarm = actualOutput.value
        if actualAlarm is None:
            actualAlarm = Alarm.get_initial_alarmstate(self.priorityFromCDB)

        newAlarm = actualAlarm.set_if(len(activeAlarms) >= self.threshold)

        if newAlarm.is_set():
            props = self.getPropsOfOutput(
                [a.props for a in activeAlarms])
            props[self.input_alarms_set_prop_name] = ",".join(
                a.id for a in activeAlarms)
        else:
            props = {}

        if newAlarm.is_set():
            mode = self.getOutputMode(
                [str(a.mode) for a in activeAlarms])
        else:
            mode = self.getOutputMode(
                [str(v.mode) for v in compInputs.values()])

        validityConstraints = self.buildValidityConstraint(
            newAlarm.is_set(), activeAlarms, inactiveAlarms)

        result = actualOutput.updateValue(newAlarm)
        result = result.updateMode(mode)
        result = result.updateProps(props)

        if validityConstraints is not None:
            result._validityConstraint = validityConstraints

        return result
